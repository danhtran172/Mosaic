const dicts: Record<Language, Dict> = { en, vi };

export type TKey = keyof Dict;
export type Translate = (key: TKey, vars?: Record<string, string | number>) => string;

export function makeTranslate(lang: Language): Translate {
  const dict = dicts[lang] ?? en;
  const terminology: Partial<Record<TKey, string>> = lang === "vi"
    ? {
        mediaSources: "Folder",
        source: "Folder",
        newFolder: "Gallery mới",
        personalFolders: "Gallery",
        addToFolder: "Thêm vào Gallery",
        addGroupToFolder: "Thêm nhóm vào Gallery",
        setFolderCover: "Đặt làm ảnh bìa Gallery",
        deleteFolder: "Xóa Gallery",
        lockFolder: "Khóa Gallery",
        unlockFolder: "Mở khóa Gallery",
        importFolder: "Nhập từ Gallery khác",
        folderName: "Tên Gallery",
        createFolder: "Tạo Gallery",
        folders: "Gallery",
        folderInfo: "Gallery",
        lockedFolder: "Gallery đã bị khóa",
      }
    : {};
  return (key, vars) => {
    let out = terminology[key] ?? dict[key] ?? en[key] ?? String(key);
    if (vars) {
      for (const [k, v] of Object.entries(vars)) out = out.replace(`{${k}}`, String(v));
    }
    return out;
  };
}

export const I18nContext = createContext<Translate>(makeTranslate("en"));
export const useT = () => useContext(I18nContext);
